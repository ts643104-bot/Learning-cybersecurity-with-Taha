function loadState() {
  try {
    const saved = JSON.parse(localStorage.getItem("mirqab-progress") || "null");
    const loaded = {
      ...initialState,
      ...(saved || {}),
      phishing: { ...initialState.phishing, ...(saved && saved.phishing || {}) },
      socCase: { ...initialState.socCase, ...(saved && saved.socCase || {}) },
      terminal: { ...initialState.terminal, ...(saved && saved.terminal || {}) }
    };
    if (saved && (saved.curriculumVersion || 1) < 2) {
      const lessonMap = {
        "foundations-1": "defense-1",
        "defense-0": "response-0",
        "defense-1": "defense-3",
        "web-1": "web-3",
        "response-0": "response-2"
      };
      loaded.completed = [...new Set(loaded.completed.map(id => lessonMap[id] || id))];
      loaded.scores = Object.fromEntries(Object.entries(loaded.scores).map(([id, score]) => [lessonMap[id] || id, score]));
      loaded.curriculumVersion = 2;
      try {
        localStorage.setItem("mirqab-progress", JSON.stringify(loaded));
      } catch (error) {
        console.warn("تعذر تحديث نسخة التقدم المحفوظ:", error);
      }
    }
    return loaded;
  } catch (error) {
    console.warn("تعذر قراءة التقدم المحفوظ:", error);
    return { ...initialState };
  }
}
